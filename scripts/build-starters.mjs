/**
 * Slice 2: design the starter library from WAVs with today's loop (Opus 5.5)
 * and write src/shared/starterSounds.ts. Costs real money (~$0.50 per sound).
 *
 *   node scripts/build-starters.mjs --yes [--only=bass-reso,keys-ep]
 *
 * Each starter keeps its provenance (the WAV it was designed from) so the
 * library drawer can show where a sound came from. Re-running a key replaces
 * just that entry; the others are kept.
 *
 * RETIRED IN SLICE 3: this drives the pre-band app (deleted). Slice 4 brings it
 * back on designs.start. The starters it built are in src/shared/starterSounds.ts.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";

import { runDesign } from "./design-run.mjs";
import { convex, withRealModel } from "./devstack.mjs";

console.error("[build-starters] retired until slice 4 (it drove the deleted pre-band app).");
process.exit(2);

if (!process.argv.includes("--yes")) {
  console.error("[build-starters] spends real API money. Re-run with --yes.");
  process.exit(2);
}

const STARTERS = [
  { starterKey: "bass-reso", role: "bass", wav: "bass_monopoly_reso_thump.wav" },
  { starterKey: "bass-sub", role: "bass", wav: "subbass_juno106.wav" },
  { starterKey: "keys-ep", role: "keys", wav: "electric_piano_jd800_soft_ep.wav" },
  { starterKey: "keys-organ", role: "keys", wav: "organ_jd800_organish.wav" },
  { starterKey: "pad-square", role: "keys", wav: "pad_jd800_fat_square.wav" },
];
const only = process.argv.find((a) => a.startsWith("--only="))?.split("=")[1]?.split(",");
const OUT = "src/shared/starterSounds.ts";
const MARK = "export const STARTER_SOUND_DATA = ";

const existing = existsSync(OUT) ? JSON.parse(readFileSync(OUT, "utf8").split(MARK)[1].replace(/;\s*$/, "")) : [];
const byKey = new Map(existing.map((s) => [s.starterKey, s]));

await withRealModel("build-starters", async () => {
  for (const st of STARTERS) {
    if (only && !only.includes(st.starterKey)) continue;
    const r = await runDesign({ wav: `samples/${st.wav}`, tag: st.starterKey });
    const final = r.slug ? convex("run", "spikes:finalPreset", JSON.stringify({ slug: r.slug })).trim() : "null";
    const parsed = JSON.parse(JSON.parse(final) ?? "null");
    const dists = r.report?.attempts?.map((a) => a.distance).filter((d) => d !== null) ?? [];
    console.log(`[${st.starterKey}] ${r.outcome} ${(r.wallMs / 1000).toFixed(1)}s turns=${r.report?.turns?.join(",")} dist=${dists.join("→")} → ${parsed?.preset?.name ?? "NO PRESET"}`);
    if (r.outcome !== "done" || !parsed) continue;
    byKey.set(st.starterKey, {
      starterKey: st.starterKey,
      name: parsed.preset.name,
      role: st.role,
      source: st.wav,
      rationale: parsed.rationale,
      designedWith: "claude-opus-5-5",
      preset: parsed.preset,
    });
  }
});

const data = STARTERS.map((s) => byKey.get(s.starterKey)).filter(Boolean);
writeFileSync(
  OUT,
  `/**\n * GENERATED by scripts/build-starters.mjs — do not edit by hand; re-run it.\n * Starter sounds designed from WAVs with today's measured loop.\n */\n\n${MARK}${JSON.stringify(data, null, 2)} as const;\n`.replace(" as const;\n", ";\n"),
);
console.log(`[build-starters] wrote ${data.length} starters to ${OUT}`);
